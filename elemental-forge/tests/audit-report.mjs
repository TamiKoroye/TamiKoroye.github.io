// Builds docs/ANIMATION-RUNTIME-AUDIT.md from a gameplay-audit run (audit.json) and the clip spec.
// Usage: node tests/audit-report.mjs <audit.json> <out.md>
import fs from 'node:fs';
const [IN, OUT] = process.argv.slice(2);
const A = JSON.parse(fs.readFileSync(IN, 'utf8'));
const spec = JSON.parse(fs.readFileSync(new URL('../tools/retarget/martial-spec.json', import.meta.url), 'utf8'));
const src = (clip) => { const b = (clip || '').split('|')[0].replace(/_M$/, ''); const s = spec.find(x => x.name === b); if (!s) return clip && /Loop|Roll|Jump/.test(clip) ? 'core library (CC0 Quaternius)' : '-'; return (s.src ? (s.src.includes('rokoko') ? 'Rokoko: ' : 'Mixamo: ') + s.src.split('/').pop() : 'CMU: ' + s.bvh) + ` ${s.start ?? 0}-${s.end ?? 'end'} s`; };
const ROWS = {
  earth: [['HAND', 'Stone Punch'], ['LEG 1', 'Earth Kick'], ['LEG 2', 'Earth Sweep'], ['GUARD', 'guard'], ['SPECIAL', 'Stone Pillar'], ['HAND held', 'hold'], ['LEG held', 'Seismic Stomp']],
  fire: [['HAND', 'Fire Fist'], ['LEG 1', 'Flame Kick'], ['LEG 2', 'Spinning Flame Kick'], ['GUARD', 'guard'], ['SPECIAL', 'Flame Orb'], ['HAND held', 'hold'], ['LEG held', 'Flying Dragon Kick']],
  water: [['HAND', 'Water Palm'], ['LEG 1', 'Crescent Water Kick'], ['LEG 2', 'Turning Wave Kick'], ['GUARD', 'guard'], ['SPECIAL', 'Water Sphere'], ['HAND held', 'hold'], ['LEG held', 'Tidal Sweep']],
  air: [['HAND', 'Air Palm'], ['LEG 1', 'Crescent Air Kick'], ['LEG 2', 'Whirlwind Kick'], ['GUARD', 'guard'], ['SPECIAL', 'Vortex'], ['HAND held', 'hold'], ['LEG held', 'Cyclone']],
};
const pct = (v) => Math.round(v * 100) + '%';
const summary = (list) => {
  if (!list.length) return null;
  const clips = [...new Set(list.map(t => t.clip.split('|')[0]))];
  const ends = {}; for (const t of list) ends[t.endedBy] = (ends[t.endedBy] || 0) + 1;
  const med = (a) => a.slice().sort((x, y) => x - y)[Math.floor(a.length / 2)];
  return { n: list.length, clips, layered: list.some(t => t.clip.endsWith('|U')), speed: [...new Set(list.map(t => t.speed))].join(' / '), shown: med(list.map(t => t.clipProgress)),
    up: list.reduce((s, t) => s + t.authoredUpper, 0) / list.length, low: list.reduce((s, t) => s + t.authoredLower, 0) / list.length, moving: list.reduce((s, t) => s + t.movingShare, 0) / list.length,
    ends: Object.entries(ends).map(([k, v]) => `${k} ${v}`).join(', ') };
};
let md = `# Runtime animation audit (Stage 1 acceptance)

Generated by \`tests/gameplay-audit.mjs\` and \`tests/audit-report.mjs\`. The game was played in Chromium at a phone landscape viewport.

**Two sessions, same move script.** Each covers all four elements: run in and attack while running, a combination, a side dodge and counter, guard, special, strafe and attack, a held HAND and a charged LEG.
- **touch:** only the on-screen controls (CDP multi-touch on the real buttons and joystick), with taps of 70-270 ms, the joystick held while attacking, element switches through the element buttons, and the rival AI fighting back.
- **demo:** the method used for the earlier demonstration videos. Presses are written straight into the controls, the rival is passive and the player does not move.

**Columns:**
- **clip:** the clip the character actually showed (from the per-frame log)
- **source:** the original file and the segment used
- **speed:** playback rate against the capture
- **shown:** the median share of the clip that played before the next action took over
- **authored:** the share of the upper and lower body driven by authored clips rather than procedural poses
- **ended by:** what ended each instance

`;
for (const el of Object.keys(ROWS)) {
  md += `\n## ${el[0].toUpperCase() + el.slice(1)}\n\n| Control | Technique | Clip(s) shown | Source | Speed | Touch: n / shown / authored upper-lower / moving | Touch: ended by | Demo: n / shown / authored upper-lower | Demo: ended by |\n|---|---|---|---|---|---|---|---|---|\n`;
  for (const [ctl, name] of ROWS[el]) {
    const t = summary(A.touch.techniques.filter(x => x.el === el && x.action === name));
    const d = summary(A.demo.techniques.filter(x => x.el === el && x.action === name));
    const any = t || d;
    if (!any) { md += `| ${ctl} | ${name} | not exercised | | | | | | |\n`; continue; }
    md += `| ${ctl} | ${name === 'guard' ? 'guard hold' : name === 'hold' ? 'sustained bending' : name} | ${any.clips.join(', ')}${t && t.layered ? ' (upper body over authored footwork while moving)' : ''} | ${any.clips.map(src).join('; ')} | ${any.speed}x | ${t ? `${t.n} / ${pct(t.shown)} / ${pct(t.up)}-${pct(t.low)} / ${pct(t.moving)}` : '-'} | ${t ? t.ends : '-'} | ${d ? `${d.n} / ${pct(d.shown)} / ${pct(d.up)}-${pct(d.low)}` : '-'} | ${d ? d.ends : '-'} |\n`;
  }
}
const all = (m) => A[m].techniques;
const other = (m, k) => all(m).filter(t => t.action === k);
md += `\n## Dodges and charge-up\n\n| | Touch: clips | Demo: clips |\n|---|---|---|\n| dodge | ${other('touch', 'dodge').map(t => t.clip).join(', ')} | ${other('demo', 'dodge').map(t => t.clip).join(', ')} |\n| charge-up (LEG held) | ${other('touch', 'charge').map(t => t.clip + ' ' + pct(t.authoredUpper)).join(', ')} | ${other('demo', 'charge').map(t => t.clip + ' ' + pct(t.authoredUpper)).join(', ')} |\n`;
md += `\nPage errors: touch ${A.touch.errors.length}, demo ${A.demo.errors.length}.\n`;
fs.writeFileSync(OUT, md);
console.log('wrote', OUT);
