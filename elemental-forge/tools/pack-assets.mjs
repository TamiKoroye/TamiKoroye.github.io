// Packages the two data assets as JavaScript modules, so the game loads them the same way it loads its own code
// (an ES module import) instead of with fetch/XHR, which some embedded hosts (e.g. the Claude app's artifact
// viewer) block while still allowing scripts.
//   assets/characters/ual-mannequin.json -> assets/characters/ual-mannequin.glb.js   (binary glTF, base64)
//   assets/animations/martial.json       -> assets/animations/martial.js             (the clip pack)
// Usage: node tools/pack-assets.mjs
import fs from 'node:fs';
const root = new URL('..', import.meta.url).pathname;
// glTF JSON with an embedded data: buffer -> GLB (JSON chunk + BIN chunk); the loader then needs no requests at all
const g = JSON.parse(fs.readFileSync(root + 'assets/characters/ual-mannequin.json', 'utf8'));
if (g.buffers.length !== 1 || !g.buffers[0].uri.startsWith('data:')) throw new Error('expected one embedded buffer');
const bin = Buffer.from(g.buffers[0].uri.split(',')[1], 'base64');
delete g.buffers[0].uri; g.buffers[0].byteLength = bin.length;
const pad = (b, v) => Buffer.concat([b, Buffer.alloc((4 - (b.length % 4)) % 4, v)]);
const json = pad(Buffer.from(JSON.stringify(g)), 0x20), body = pad(bin, 0);
const head = Buffer.alloc(12), jh = Buffer.alloc(8), bh = Buffer.alloc(8);
head.writeUInt32LE(0x46546c67, 0); head.writeUInt32LE(2, 4); head.writeUInt32LE(12 + 8 + json.length + 8 + body.length, 8);
jh.writeUInt32LE(json.length, 0); jh.writeUInt32LE(0x4e4f534a, 4); bh.writeUInt32LE(body.length, 0); bh.writeUInt32LE(0x004e4942, 4);
const glb = Buffer.concat([head, jh, json, bh, body]);
fs.writeFileSync(root + 'assets/characters/ual-mannequin.glb.js',
  `// CC0 Quaternius Universal Animation Library mannequin, binary glTF (base64). Generated by tools/pack-assets.mjs\nexport const BYTES = ${glb.length};\nexport default ${JSON.stringify(glb.toString('base64'))};\n`);
const pack = fs.readFileSync(root + 'assets/animations/martial.json', 'utf8');
const n = JSON.parse(pack).clips.length;
fs.writeFileSync(root + 'assets/animations/martial.js', `// Martial-arts clip pack (${n} clips). Generated by tools/pack-assets.mjs from martial.json\nexport const CLIP_COUNT = ${n};\nexport default ${pack};\n`);
console.log('glb', glb.length, 'bytes; pack', n, 'clips');
